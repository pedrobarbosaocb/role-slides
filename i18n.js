const LANG_KEY = 'role_slides_lang_v1';
let current = 'pt';

export function detectLang() {
    try {
        const saved = localStorage.getItem(LANG_KEY);
        if (saved && DICTS[saved]) return saved;
    } catch { /* sem storage */ }
    const nav = (navigator.language || 'pt').slice(0, 2).toLowerCase();
    return DICTS[nav] ? nav : 'pt';
}

export function setLang(code) {
    current = DICTS[code] ? code : 'pt';
    try { localStorage.setItem(LANG_KEY, current); } catch { /* sem storage */ }
    const meta = LANGS.find(l => l.code === current);
    document.documentElement.lang = meta.html;
    document.documentElement.dir = meta.dir;
    document.title = t('page_title');
    document.querySelectorAll('[data-i18n]').forEach(el => { el.textContent = t(el.dataset.i18n); });
    document.querySelectorAll('[data-i18n-ph]').forEach(el => { el.placeholder = t(el.dataset.i18nPh); });
    document.querySelectorAll('[data-i18n-aria]').forEach(el => { el.setAttribute('aria-label', t(el.dataset.i18nAria)); });
    document.querySelectorAll('[data-i18n-title]').forEach(el => { el.title = t(el.dataset.i18nTitle); });
}

export const getLang = () => current;

export function t(key, vars = {}) {
    const str = DICTS[current][key] ?? pt[key] ?? key;
    return str.replace(/\{(\w+)\}/g, (_, k) => (vars[k] ?? `{${k}}`));
}
